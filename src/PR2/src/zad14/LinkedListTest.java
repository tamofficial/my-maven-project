package zad14;

import java.util.LinkedList; // Импортируем класс LinkedList из пакета java.util

public class LinkedListTest {
    public static void main(String[] args) {
        // Создание коллекции LinkedList
        LinkedList<String> states = new LinkedList<>();
        // Создаём объект LinkedList для хранения строк. Он начинается как пустой список.

        // Добавление элементов в список
        states.add("Германия");
        // Добавляем строку "Германия" в конец списка

        states.add("Франция");
        // Добавляем строку "Франция" в конец списка

        states.addLast("Великобритания");
        // Добавляем строку "Великобритания" в конец списка (аналогично add(), но через метод addLast)

        states.addFirst("Испания");
        // Добавляем строку "Испания" в начало списка с помощью метода addFirst()

        states.add(1, "Италия");
        // Добавляем строку "Италия" на второй индекс (между Германией и Францией)

        // Вывод количества элементов
        System.out.printf("В списке %d элементов\n", states.size());
        // Метод size() возвращает количество элементов в списке. Ожидаем, что выведется "В списке 5 элементов".

        // Получение элемента по индексу
        System.out.println("Элемент на втором месте: " + states.get(1));
        // Метод get(1) получает элемент с индексом 1 (в данном случае "Италия"). Выводим его на экран.

        // Замена элемента
        states.set(1, "Дания");
        // Метод set(1, "Дания") заменяет элемент на индексе 1 ("Италия") на "Дания".

        // Вывод всех элементов списка
        System.out.println("Список элементов:");
        for (String state : states) {
            System.out.println(state);
        }
        // Цикл for-each перебирает все элементы списка и выводит их на экран. После изменений вывод будет:
        // Испания
        // Германия
        // Дания
        // Франция
        // Великобритания

        // Проверка наличия элемента
        if (states.contains("Германия")) {
            System.out.println("Список содержит Германию.");
        }
        // Метод contains("Германия") проверяет, есть ли в списке строка "Германия".
        // Если да, выводим "Список содержит Германию", так как "Германия" была добавлена ранее.

        // Удаление элементов
        states.remove("Германия");
        // Метод remove("Германия") удаляет первый найденный элемент "Германия" из списка.

        states.removeFirst();
        // Метод removeFirst() удаляет первый элемент в списке. После удаления "Германия", первым будет "Испания", и она будет удалена.

        states.removeLast();
        // Метод removeLast() удаляет последний элемент в списке. После удаления "Испания" и "Германия", последним будет "Великобритания", и он будет удалён.

        // Работа с объектами в списке
        LinkedList<Person> people = new LinkedList<>();
        // Создаём новый список, который будет хранить объекты типа Person.

        people.add(new Person("Mike"));
        // Добавляем объект Person с именем "Mike" в конец списка

        people.addFirst(new Person("Tom"));
        // Добавляем объект Person с именем "Tom" в начало списка с помощью метода addFirst()

        people.addLast(new Person("Nick"));
        // Добавляем объект Person с именем "Nick" в конец списка с помощью метода addLast()

        people.remove(1);
        // Метод remove(1) удаляет второй элемент в списке (индекс 1), т.е. объект Person с именем "Tom".

        System.out.println("Список объектов Person:");
        // Выводим сообщение о том, что сейчас будем выводить список объектов класса Person.

        for (Person person : people) {
            System.out.println(person.getName());
        }
        // Цикл for-each перебирает все объекты в списке people и вызывает для каждого объекта метод getName() для вывода имени.
        // Ожидаемый вывод:
        // Mike
        // Nick

        // Получение первого элемента
        Person first = people.getFirst();
        // Метод getFirst() возвращает первый элемент в списке, в данном случае объект Person с именем "Mike".

        System.out.println("Первый объект: " + first.getName());
        // Выводим имя первого объекта в списке. Ожидаемый вывод: "Первый объект: Mike"
    }
}

// Класс Person
class Person {
    private String name;

    public Person(String value) {
        name = value;
    }

    public String getName() {
        return name;
    }
}